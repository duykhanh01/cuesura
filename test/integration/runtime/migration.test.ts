// Fixture generated by test/support/store-flows.ts mixedWorkload with the schema-1 store at commit af5df8d.
const FIXTURE = fileURLToPath(new URL('../../fixtures/runtime/db/v1.sqlite', import.meta.url));
const FIXTURE_SHA256 = readFileSync(
  new URL('../../fixtures/runtime/db/v1.sha256', import.meta.url),
  'utf8',
).split(/\s+/)[0];
const tempDir = useTempDir('cusr-migrate-');

const SOURCE_TABLES = [
  'events',
  'accepted_triggers',
  'frozen_policies',
  'frozen_contexts',
] as const;

function dump(db: Database.Database, table: string): unknown[] {
  return db.prepare(`SELECT * FROM ${table} ORDER BY rowid`).all();
}

function copyFixture(): string {
  const path = join(tempDir(), 'cusr.sqlite');
  copyFileSync(FIXTURE, path);
  return path;
}

describe('migration 006: one execution slot row per holding task', () => {
  it('keeps the held slot, orders it by its grant and still verifies', () => {
    const path = join(tempDir(), 'cusr.sqlite');
    const d = new StoreDriver(openFileStoreForTest(path));
    const t = buildTask();
    d.must(t.id, { kind: 'create_task', task: t });
    d.must(t.id, { kind: 'request_execution' });
    const g = d.store.grantNext(d.now as EpochMs);
    expect(g.ok && g.value.kind).toBe('decided');
    const held = d.store.readSlots();
    expect(held).toHaveLength(1);
    d.store.close();

    // Back to the singleton table of schema 5, holding the same slot.
    const raw = new Database(path);
    raw.exec(`DROP TABLE execution_slot;
      CREATE TABLE execution_slot (
        key TEXT PRIMARY KEY CHECK (key = 'execution'),
        holder_task_id TEXT NOT NULL,
        request_id TEXT NOT NULL UNIQUE,
        claimed_at INTEGER NOT NULL
      ) STRICT;`);
    raw
      .prepare(
        `INSERT INTO execution_slot (key, holder_task_id, request_id, claimed_at) VALUES ('execution', ?, ?, ?)`,
      )
      .run(held[0]?.holder_task_id, held[0]?.request_id, held[0]?.claimed_at);
    raw.prepare('UPDATE schema_meta SET version = 5').run();
    raw.close();

    const store = openFileStoreForTest(path);
    expect(store.readSlots()).toEqual(held);
    expect(store.verifyProjections()).toMatchObject({ ok: true, mismatches: [] });
    store.close();
  });
});

describe('migration 004: the project of a command', () => {
  function atVersion3(path: string): Database.Database {
    const raw = new Database(path);
    raw.exec('ALTER TABLE command_ledger DROP COLUMN project');
    raw.prepare('UPDATE schema_meta SET version = 3').run();
    return raw;
  }

  it('backfills rows that have a task and leaves the others NULL, keeping every other column', () => {
    const path = copyFixture();
    openFileStoreForTest(path).close();
    const raw = atVersion3(path);
    const task = raw.prepare('SELECT id, project FROM tasks LIMIT 1').get() as {
      id: string;
      project: string;
    };
    const insert = raw.prepare(
      `INSERT INTO command_ledger (request_id, actor, kind, command_hash, task_id, assigned_ids_json, status, admitted_at)
       VALUES (?, 'owner', 'task_cancel', 'h', ?, '[]', 'admitted', 1)`,
    );
    insert.run('with-task', task.id);
    insert.run('gone-task', '00000000-0000-7000-8000-00000000dead');
    insert.run('no-task', null);
    const before = raw.prepare('SELECT * FROM command_ledger ORDER BY request_id').all();
    raw.close();

    openFileStoreForTest(path).close();
    const after = new Database(path, { readonly: true });
    const rows = after.prepare('SELECT * FROM command_ledger ORDER BY request_id').all() as {
      request_id: string;
      project: string | null;
    }[];
    after.close();
    expect(Object.fromEntries(rows.map((r) => [r.request_id, r.project]))).toEqual({
      'gone-task': null,
      'no-task': null,
      'with-task': task.project,
    });
    expect(rows.map(({ project: _p, ...rest }) => rest)).toEqual(before);
  });

  it('leaves events and triggers untouched', () => {
    const path = copyFixture();
    openFileStoreForTest(path).close();
    const raw = atVersion3(path);
    const before = Object.fromEntries(SOURCE_TABLES.map((t) => [t, dump(raw, t)]));
    raw.close();
    openFileStoreForTest(path).close();
    const after = new Database(path, { readonly: true });
    for (const t of SOURCE_TABLES) expect(dump(after, t), t).toEqual(before[t]);
    after.close();
  });
});

describe('migration 001 → 002 on a real schema-1 database', () => {
  it('fixture is the recorded schema-1 database', () => {
    expect(createHash('sha256').update(readFileSync(FIXTURE)).digest('hex')).toBe(FIXTURE_SHA256);
    const db = new Database(copyFixture(), { readonly: true });
    expect(db.prepare('SELECT version FROM schema_meta').get()).toEqual({
      version: 1,
    });
    db.close();
  });

  it('keeps raw events, triggers and snapshots byte-identical and rebuilds projections that verify', () => {
    const path = copyFixture();
    const v1 = new Database(path, { readonly: true });
    const before = Object.fromEntries(SOURCE_TABLES.map((t) => [t, dump(v1, t)]));
    v1.close();

    const store = openFileStoreForTest(path);
    const db = storeDb(store);
    expect(db.prepare('SELECT version FROM schema_meta').get()).toEqual({
      version: SCHEMA_VERSION,
    });
    expect(SCHEMA_VERSION).toBe(7);
    for (const t of SOURCE_TABLES) expect(dump(db, t), t).toEqual(before[t]);

    expect(store.verifyProjections()).toMatchObject({
      ok: true,
      mismatches: [],
    });
    const tasks = db.prepare('SELECT id, state_json FROM tasks').all() as {
      id: string;
      state_json: string;
    }[];
    expect(tasks.length).toBeGreaterThan(0);
    for (const { id, state_json } of tasks) {
      const rows = db
        .prepare('SELECT * FROM events WHERE task_id = ? ORDER BY seq')
        .all(id) as EventRow[];
      const state = JSON.parse(state_json) as ReturnType<typeof replay>;
      expect(state).toEqual(replay(rows.map(toEvent)));
      expect(state).toMatchObject({
        runtime_ref: null,
        operations: {},
        completion: null,
        execution: { request: null, holding: null },
      });
    }
    for (const t of [
      'runtime_contexts',
      'execution_queue',
      'execution_slot',
      'operations',
      'command_ledger',
    ]) {
      expect(db.prepare(`SELECT COUNT(*) AS n FROM ${t}`).get(), t).toEqual({
        n: 0,
      });
    }
    store.close();
  });

  it('a migrated legacy task stays read-only for the 002 claim path', () => {
    const store = openFileStoreForTest(copyFixture());
    const pending = store.pendingEffects(100);
    expect(pending.length).toBeGreaterThan(0);
    for (const e of pending) {
      expect(
        store.claimEffect(e.id as Uuid, 0 as EpochMs, {
          require_runtime: true,
        }),
      ).toMatchObject({
        ok: false,
        error: { code: 'claim_blocked', reason: 'legacy_task' },
      });
    }
    store.close();
  });

  it('rolls the whole migration back when the rebuild fails, leaving schema 1 untouched', () => {
    const path = copyFixture();
    const raw = new Database(path);
    // A log that cannot replay makes the rebuild throw inside the migration transaction.
    raw
      .prepare(
        `UPDATE events SET type = 'TaskCompleted', payload_json = '{"reason":"x"}' WHERE global_seq = (SELECT MIN(global_seq) FROM events)`,
      )
      .run();
    const before = Object.fromEntries(SOURCE_TABLES.map((t) => [t, dump(raw, t)]));
    raw.close();

    expect(() => openFileStoreForTest(path)).toThrow();
    const after = new Database(path, { readonly: true });
    expect(after.prepare('SELECT version FROM schema_meta').get()).toEqual({
      version: 1,
    });
    expect(
      after.prepare(`SELECT name FROM sqlite_master WHERE name = 'execution_slot'`).get(),
    ).toBeUndefined();
    for (const t of SOURCE_TABLES) expect(dump(after, t), t).toEqual(before[t]);
    after.close();
  });

  it('a database newer than the code is refused without being touched', () => {
    const path = copyFixture();
    const raw = new Database(path);
    raw.prepare('UPDATE schema_meta SET version = ?').run(SCHEMA_VERSION + 1);
    raw.close();
    const r = openStore(path);
    expect(r).toMatchObject({
      ok: false,
      error: { code: 'schema_incompatible' },
    });
    const after = new Database(path, { readonly: true });
    expect(after.prepare('SELECT version FROM schema_meta').get()).toEqual({
      version: SCHEMA_VERSION + 1,
    });
    after.close();
  });
});

describe('migration 005: the decider budget', () => {
  it('rewrites task state without decider_calls and keeps the event log and snapshots', () => {
    const path = copyFixture();
    const before = new Database(path);
    const source = SOURCE_TABLES.map((t) => dump(before, t));
    before.close();

    const opened = openFileStoreForTest(path);
    const db = storeDb(opened);
    const rows = db.prepare('SELECT state_json FROM tasks').all() as {
      state_json: string;
    }[];
    expect(rows.length).toBeGreaterThan(0);
    for (const r of rows) expect(r.state_json).not.toContain('decider_calls');
    expect(SOURCE_TABLES.map((t) => dump(db, t))).toEqual(source);
    expect(opened.verifyProjections().mismatches).toEqual([]);
    opened.close();
  });
});
